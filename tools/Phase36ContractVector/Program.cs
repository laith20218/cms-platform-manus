using System.Text;
using System.Text.Json;
using CMS.Infrastructure.Services;
using Microsoft.Extensions.Configuration;

var manifestSigningKey = Enumerable.Range(33, 32).Select(value => (byte)value).ToArray();
var wrappingKey = Enumerable.Range(1, 32).Select(value => (byte)value).ToArray();
var configuration = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string?>
{
    ["Security:Offline:KeyWrappingKey"] = Convert.ToBase64String(wrappingKey),
    ["Security:Offline:ManifestSigningKey"] = Convert.ToBase64String(manifestSigningKey)
}).Build();

var service = new OfflinePackageCryptoService(configuration);
var userId = Guid.Parse("aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa");
var subjectId = Guid.Parse("bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb");
var installationId = "phase36-device-a";
var issuedAt = new DateTime(2030, 1, 1, 0, 0, 0, DateTimeKind.Utc);
var expiresAt = issuedAt.AddHours(2);
var plaintext = Encoding.UTF8.GetBytes("phase36-contract-vector-medical-content");
var package = service.Encrypt(userId, installationId, 3, new[] { subjectId }, issuedAt, expiresAt, plaintext);
var packageKey = service.ReleaseKey(package, userId, installationId, issuedAt.AddMinutes(1));

var document = new
{
    schemaVersion = 1,
    testOnly = true,
    note = "Generated by Phase36ContractVector from OfflinePackageCryptoService. Test-only keys must never ship in an APK.",
    expectedUserId = userId,
    expectedSubjectId = subjectId,
    expectedInstallationId = installationId,
    verificationTimeUtc = issuedAt.AddMinutes(1),
    testOnlyManifestSigningKeyBase64 = Convert.ToBase64String(manifestSigningKey),
    testOnlyPackageKeyBase64 = Convert.ToBase64String(packageKey),
    envelope = new
    {
        manifest = new
        {
            packageId = package.Manifest.PackageId,
            userId = package.Manifest.UserId,
            installationId = package.Manifest.InstallationId,
            contentVersion = package.Manifest.ContentVersion,
            allowedSubjects = package.Manifest.AllowedSubjects,
            issuedAt = package.Manifest.IssuedAt,
            expiresAt = package.Manifest.ExpiresAt,
            nonceBase64Url = package.Manifest.NonceBase64Url,
            aadHashBase64Url = package.Manifest.AadHashBase64Url,
            signatureBase64Url = package.Manifest.SignatureBase64Url
        },
        ciphertextBase64Url = package.CiphertextBase64Url,
        tagBase64Url = package.TagBase64Url,
        wrappedKeyBase64Url = package.WrappedKeyBase64Url,
        keyReleaseToken = package.KeyReleaseToken
    },
    expectedPlaintextUtf8 = Encoding.UTF8.GetString(plaintext)
};

var output = args.Length == 1 ? args[0] : "phase36-contract-vector.json";
Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
await File.WriteAllTextAsync(output, JsonSerializer.Serialize(document, new JsonSerializerOptions
{
    WriteIndented = true,
    PropertyNamingPolicy = JsonNamingPolicy.CamelCase
}));
Console.WriteLine(output);
